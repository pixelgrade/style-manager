import _ from 'lodash';

export const PALETTE_OUTPUT_SETTING_ID = 'sm_advanced_palette_output';
export const FONT_PALETTE_SETTING_ID = 'sm_font_palette';
export const FONT_SIZING_BASELINE_SETTING_ID = 'sm_font_sizing_baseline_v1';

export const FREE_PALETTE_SETTING_IDS = [
  'sm_advanced_palette_source',
  'sm_color_palette_in_use',
  'sm_is_custom_color_palette',
];

const hasOwn = ( object, key ) => Object.prototype.hasOwnProperty.call( object, key );

const isPlainObject = value => value && 'object' === typeof value && ! Array.isArray( value );

/**
 * Deep equality where the "no value" spellings count as the same thing:
 * PHP-saved font configs store `false`, the JS engine recomputes `null` or
 * `NaN` (parseFloat of false) for the same empty subfields.
 */
const isNoValue = v => false === v || null === v || undefined === v || ( 'number' === typeof v && isNaN( v ) );
// Checkboxes produce booleans where PHP stored '1' / '' / '0'.
export const isTruthyBool = v => true === v || '1' === v;
const isFalsyBool = v => false === v || '' === v || '0' === v;

const isEquivalentValue = ( a, b ) => _.isEqualWith( a, b, ( x, y ) => {
  if ( isNoValue( x ) && isNoValue( y ) ) {
    return true;
  }
  if ( ( 'boolean' === typeof x || 'boolean' === typeof y ) && (
    ( isTruthyBool( x ) && isTruthyBool( y ) ) || ( isFalsyBool( x ) && isFalsyBool( y ) )
  ) ) {
    return true;
  }
  // Native range/number inputs emit numbers where PHP stored numeric strings.
  if ( ( 'number' === typeof x || 'number' === typeof y )
    && '' !== x && '' !== y && null !== x && null !== y
    && isFinite( Number( x ) ) && isFinite( Number( y ) )
    && Number( x ) === Number( y ) ) {
    return true;
  }
  return undefined;
} );

const isThemeFontOption = id => /\[[^\]]*font[^\]]*\]$/.test( id );

const getLockedFontPaletteIds = plusPayload => {
  const fontPalettes = plusPayload && plusPayload.fontPalettes;
  const lockedIds = fontPalettes && Array.isArray( fontPalettes.lockedIds )
    ? fontPalettes.lockedIds
    : [];

  return new Set( lockedIds.map( id => String( id ) ) );
};

const hasLockedFontPaletteChange = ( changedValues, plusPayload ) => {
  if ( ! plusPayload || ! plusPayload.locked || ! hasOwn( changedValues, FONT_PALETTE_SETTING_ID ) ) {
    return false;
  }

  return getLockedFontPaletteIds( plusPayload ).has( String( changedValues[ FONT_PALETTE_SETTING_ID ] ) );
};

const isDefaultMaterializedFontValue = ( key, value, baselineValue, candidateValue ) => {
  if ( 'font_variant' === key ) {
    return !! baselineValue.font_family && baselineValue.font_family === candidateValue.font_family;
  }
  if ( 'letter_spacing' === key ) {
    return isEquivalentValue( value, { value: 0, unit: 'em' } );
  }
  if ( 'text_transform' === key ) {
    return 'none' === value || isNoValue( value );
  }
  if ( 'line_height' === key ) {
    return isEquivalentValue( value, { value: null, unit: false } ) || isNoValue( value );
  }
  return false;
};

const normalizeMaterializedFontDefaults = ( id, baselineValue, candidateValue ) => {
  if ( ! isThemeFontOption( id ) || ! isPlainObject( baselineValue ) || ! isPlainObject( candidateValue ) ) {
    return candidateValue;
  }

  const normalized = { ...candidateValue };

  Object.keys( normalized ).forEach( key => {
    if ( hasOwn( baselineValue, key ) ) {
      return;
    }

    if ( isDefaultMaterializedFontValue( key, normalized[ key ], baselineValue, candidateValue ) ) {
      delete normalized[ key ];
    }
  } );

  return normalized;
};

export const isEquivalentSettingValue = ( id, baselineValue, candidateValue ) => isEquivalentValue(
  baselineValue,
  normalizeMaterializedFontDefaults( id, baselineValue, candidateValue )
);

export const getChangedSettingsValues = ( dirtyValues = {}, baselineSettings = {} ) => {
  const changed = {};

  Object.entries( dirtyValues ).forEach( ( [ id, value ] ) => {
    if ( baselineSettings[ id ] && isEquivalentSettingValue( id, baselineSettings[ id ].value, value ) ) {
      return;
    }
    changed[ id ] = value;
  } );

  return changed;
};

/**
 * Remove Plus trial-only changes before mirroring Site Editor edits into
 * core-data. Trial controls still update the live preview through wp.customize,
 * but they must not make WordPress present a savable Style Manager entity.
 *
 * `sm_advanced_palette_output` needs special handling: it is generated by the
 * palette builder and is also used for free palette-source changes. Allow it
 * only when a free palette setting changed and no direct Plus tuning setting
 * changed in the same edit batch.
 *
 * @param {Object} changedValues Setting id => value map from wp.customize.
 * @param {Object} plusPayload   Localized Plus payload.
 *
 * @return {Object} Filtered setting id => value map.
 */
export const filterLockedPlusChangedValues = ( changedValues = {}, plusPayload = null ) => {
  const filtered = { ...changedValues };

  if ( ! plusPayload || ! plusPayload.locked ) {
    return filtered;
  }

  const gatedSettingIds = new Set( Array.isArray( plusPayload.gatedSettingIds )
    ? plusPayload.gatedSettingIds
    : [] );
  const hasGatedSettingChange = Object.keys( changedValues ).some( id => gatedSettingIds.has( id ) );
  const hasLockedPaletteChange = hasLockedFontPaletteChange( changedValues, plusPayload );

  gatedSettingIds.forEach( id => {
    delete filtered[ id ];
  } );

  // This hidden value is client-side round-trip state, not an authority. The
  // locked server rebuilds and mirrors a safe copy whenever the free named
  // Font Sizing driver is saved. Suppress it even when it is the only dirty
  // setting, otherwise WordPress attempts an empty save after server gating.
  delete filtered[ FONT_SIZING_BASELINE_SETTING_ID ];

  if ( hasLockedPaletteChange ) {
    delete filtered[ FONT_PALETTE_SETTING_ID ];
  }

  if ( hasOwn( changedValues, PALETTE_OUTPUT_SETTING_ID ) ) {
    const hasFreePaletteChange = FREE_PALETTE_SETTING_IDS.some( id => hasOwn( changedValues, id ) );

    if ( hasGatedSettingChange || hasLockedPaletteChange || ! hasFreePaletteChange ) {
      delete filtered[ PALETTE_OUTPUT_SETTING_ID ];
    }
  }

  return filtered;
};

/**
 * The genuinely Plus-gated subset of changed values: changes whose setting id
 * is in `plusPayload.gatedSettingIds` while the trial is locked. These are the
 * trial-only refinements that update the live preview but can never be
 * persisted — the set that drives the "Save · Plus" affordance.
 *
 * This is intentionally NOT the full inverse of
 * `filterLockedPlusChangedValues`. That filter also strips the generated
 * `sm_advanced_palette_output` blob when it is an orphan (present without any
 * free palette-source change) — that suppression is boot/round-trip churn, not
 * a gated refinement. Counting it here would raise a phantom "Save · Plus" with
 * no real gated change, so the orphan is deliberately excluded.
 *
 * @param {Object} changedValues Setting id => value map from wp.customize.
 * @param {Object} plusPayload   Localized Plus payload.
 *
 * @return {Object} The gated subset: setting id => value map.
 */
export const getGatedChangedValues = ( changedValues = {}, plusPayload = null ) => {
  if ( ! plusPayload || ! plusPayload.locked ) {
    return {};
  }

  const gatedSettingIds = new Set( Array.isArray( plusPayload.gatedSettingIds )
    ? plusPayload.gatedSettingIds
    : [] );

  return Object.fromEntries(
    Object.entries( changedValues ).filter( ( [ id ] ) => gatedSettingIds.has( id ) )
  );
};

// Higher-level typography controls that RE-DERIVE the per-category font settings
// (master family + elevation/pitch, and the theme font targets) as a side
// effect: the global font sizing and the font-palette selection. When one of
// these drives the change, the per-category font edits are not deliberate
// individual tweaks. (Neither driver is itself in the gated set.)
export const TYPOGRAPHY_CASCADE_DRIVER_IDS = [ 'sm_font_sizing', 'sm_font_palette' ];
export const CONNECTED_FIELDS_PRESET_SETTING_ID = 'sm_fonts_connected_fields_preset';

// A gated id is a per-category font *output* (master family `sm_font_primary…`,
// or its `…_elevation` / `…_pitch`) — i.e. something a palette/sizing change
// re-derives. The drivers themselves are never gated, but exclude them anyway.
const isPerCategoryFontOutputId = id => /^sm_font_/.test( id ) && ! TYPOGRAPHY_CASCADE_DRIVER_IDS.includes( id );

const matchesDirectGatedSettingValue = ( id, value, plusPayload ) => {
  const expectedValues = plusPayload && isPlainObject( plusPayload.directGatedSettingValues )
    ? plusPayload.directGatedSettingValues
    : {};

  if ( ! hasOwn( expectedValues, id ) ) {
    return false;
  }

  const expected = expectedValues[ id ];
  if ( isPlainObject( expected ) && isPlainObject( value ) ) {
    return Object.keys( expected ).every( key => isEquivalentValue( expected[ key ], value[ key ] ) );
  }

  return isEquivalentValue( expected, value );
};

/**
 * The gated changes that represent a *deliberate* premium refinement — the
 * signal that drives the "Save · Plus" affordance. Two rules narrow the raw
 * gated set so derived typography outputs don't light up the gate on their own:
 *
 *   1. Derived theme font targets (`anima_options[…font]`) are pure rendered
 *      outputs — never individually tuned — so they never count as a signal.
 *   2. Per-category font settings (master family + elevation/pitch) ARE premium
 *      controls, but only an *individual* tweak counts: drop them when a
 *      higher-level driver (font sizing or font-palette selection) re-derived
 *      them in the same batch.
 *
 * Heuristic by design: changing font sizing/palette AND individually tuning a
 * per-category font in the same unsaved batch suppresses the latter's signal.
 * The persistence gate is unaffected — filterLockedPlusChangedValues() still
 * strips every gated id on save; this only narrows the affordance's signal.
 * Scoped to typography; the color side is untouched.
 *
 * @param {Object} changedValues Setting id => value map from wp.customize.
 * @param {Object} plusPayload   Localized Plus payload.
 *
 * @return {Object} The deliberate-refinement gated subset.
 */
export const getSignalGatedChangedValues = ( changedValues = {}, plusPayload = null ) => {
  const gated = getGatedChangedValues( changedValues, plusPayload );
  const drivenByHigherLevel = TYPOGRAPHY_CASCADE_DRIVER_IDS.some( id => hasOwn( changedValues, id ) );
  const drivenByFontPalette = hasOwn( changedValues, FONT_PALETTE_SETTING_ID );
  const lockedPaletteSignal = hasLockedFontPaletteChange( changedValues, plusPayload )
    ? { [ FONT_PALETTE_SETTING_ID ]: changedValues[ FONT_PALETTE_SETTING_ID ] }
    : {};

  return {
    ...lockedPaletteSignal,
    ...Object.fromEntries(
      Object.entries( gated ).filter( ( [ id ] ) => {
        if ( isThemeFontOption( id ) && ! matchesDirectGatedSettingValue( id, changedValues[ id ], plusPayload ) ) {
          return false;
        }
        if ( drivenByFontPalette && CONNECTED_FIELDS_PRESET_SETTING_ID === id ) {
          return false;
        }
        if ( drivenByHigherLevel && isPerCategoryFontOutputId( id ) ) {
          return false;
        }
        return true;
      } )
    ),
  };
};

export const getBaselineSettingsValues = ( settings = {} ) => Object.entries( settings ).reduce(
  ( values, [ id, data ] ) => {
    values[ id ] = data && hasOwn( data, 'value' ) ? data.value : data;
    return values;
  },
  {}
);

export const clearNativeSaveEdits = ( coreDispatch, kind, name, recordId, persistedSettings = {} ) => {
  if ( coreDispatch && 'function' === typeof coreDispatch.clearEntityRecordEdits ) {
    coreDispatch.clearEntityRecordEdits( kind, name, recordId );
    return;
  }

  if ( coreDispatch && 'function' === typeof coreDispatch.editEntityRecord ) {
    coreDispatch.editEntityRecord( kind, name, recordId, { settings: persistedSettings } );
  }
};
